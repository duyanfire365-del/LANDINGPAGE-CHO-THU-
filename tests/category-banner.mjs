import assert from 'node:assert/strict';
import {access} from 'node:fs/promises';
import {categoryBanner,withCategoryBanner} from '../lib/listing-banner.mjs';
import {standardizeListing} from '../lib/listing-identity.mjs';
for(const type of ['Kho xưởng','Mặt bằng kinh doanh','Nhà nguyên căn','Đất cho thuê','Văn phòng','Phòng trọ','Căn hộ chung cư','Căn hộ dịch vụ','Ki-ốt','Biệt thự, nhà liền kề','Bất động sản khác'])await access(new URL('../public'+categoryBanner(type),import.meta.url));
const old={type:'Kho xưởng',size:100,address:'Thanh Xuân',image:'/banner.png',media:[]};
assert.match(standardizeListing(old,1).image,/^\/illustrations\/kx-/);
assert.match(standardizeListing({...old,type:'Mặt bằng kinh doanh',image:'/banners/kx.png'},1).image,/^\/illustrations\/mb-/);
const real={...old,image:'/api/files?action=media&id=photo',media:[{kind:'image',id:'photo'}]};assert.deepEqual(withCategoryBanner(real),real);
const ai={...real,illustrationKind:'ai'};assert.deepEqual(withCategoryBanner(ai),ai);
console.log('PASS: all category banners exist, old banner-only posts upgrade, category changes update banners, and supplied photos/previous AI images remain unchanged.');
