import assert from 'node:assert/strict';
import {houseBusinessCategories,inferCategory} from '../lib/listing-content.mjs';
import {standardizeRows} from '../lib/listing-identity.mjs';
import {extractByRules} from '../lib/source-rules.mjs';
const text='Sang nhượng quán ăn phố Thái Hà – Nhà riêng biệt 3 tầng\nDiện tích: 60m² × 3 tầng\nNhà riêng biệt, thuận tiện tổ chức kinh doanh\nGiá thuê: 28 triệu/tháng';
assert.equal(inferCategory(text),'Mặt bằng kinh doanh');
assert.equal(extractByRules(text).type,'Mặt bằng kinh doanh');
assert.deepEqual(houseBusinessCategories(text),['Mặt bằng kinh doanh','Nhà nguyên căn']);
for(const text of ['Nhà nguyên căn gần quán ăn','Căn hộ chung cư gần quán ăn','Nhà nguyên căn chỉ để ở'])assert.equal(houseBusinessCategories(text),null);
const old={id:'a',created_at:'2026-01-01',status:'published',public_data:{title:'Sang nhượng nhà nguyên căn 60 m² — Thái Hà',titleMode:'custom',description:text,type:'Nhà nguyên căn',categories:['Nhà nguyên căn'],size:60,code:'NC - 0007',listingSequence:7,slug:'live-1234567890123',media:[{id:'photo'}],address:'Thái Hà, Đống Đa'}};
const repaired=standardizeRows([old])[0];
assert.match(repaired.public_data.code,/^MB - /);
assert.deepEqual(repaired.public_data.categories,['Mặt bằng kinh doanh','Nhà nguyên căn']);
assert(repaired.public_data.legacyCodes.includes('NC - 0007'));
assert.equal(repaired.public_data.slug,old.public_data.slug);
assert.deepEqual(repaired.public_data.media,old.public_data.media);
assert.deepEqual(standardizeRows([repaired])[0],repaired);
assert.equal(standardizeRows([{...old,public_data:{...old.public_data,categoryMode:'manual'}}])[0].public_data.type,'Nhà nguyên căn');
console.log('PASS: Thai Ha restaurant uses MB, both category filters match, old code retained, URLs/photos preserved; residential and nearby-business negatives and manual override protected.');
